export function verifyTag(tag: string, directory = root): string {
  assert.match(
    tag,
    /^v(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/,
    "Expected a release tag such as v0.0.1",
  );
  const version = tag.slice(1);
  const main = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
  assert.strictEqual(main.name, "astro-compiler-zig");
  assert.strictEqual(main.version, version, "Tag and package.json version differ");
  assert.strictEqual(main.optionalDependencies, undefined);
  const zon = readFileSync(join(directory, "build.zig.zon"), "utf8");
  assert.strictEqual(
    /\.version = "([^"]+)"/.exec(zon)?.[1],
    version,
    "Zig package version differs",
  );
  return version;
}

async function transferDecoder(): Promise<string> {
  const result = await $`zig build generate-transfer -j1`
    .cwd(root)
    .stdout("piped")
    .stderr("piped")
    .noThrow();
  if (result.code !== 0) throw new Error(result.stderr);
  const output = result.stderr
    .replace("'use strict';\n", "")
    .replace("module.exports = ", "export ");
  if (!output.startsWith("// Generated by")) throw new Error("Invalid generated decoder");
  return output;
}

async function tsxData(): Promise<string> {
  const astroComment =
    "/**\n * Astro global available in all contexts in .astro files\n *\n * [Astro documentation](https://docs.astro.build/reference/api-reference/#astro-global)\n*/\n";
  const inferredTypes =
    "type ASTRO__ArrayElement<ArrayType extends readonly unknown[]> = ArrayType extends readonly (infer ElementType)[] ? ElementType : never;\n" +
    "type ASTRO__Flattened<T> = T extends Array<infer U> ? ASTRO__Flattened<U> : T;\n" +
    "type ASTRO__InferredGetStaticPath = ASTRO__Flattened<ASTRO__ArrayElement<Awaited<ReturnType<typeof getStaticPaths>>>>;\n" +
    "type ASTRO__MergeUnion<T, K extends PropertyKey = T extends unknown ? keyof T : never> = T extends unknown ? T & { [P in Exclude<K, keyof T>]?: never } extends infer O ? { [P in keyof O]: O[P] } : never : never;\n" +
    "type ASTRO__Get<T, K> = T extends undefined ? undefined : K extends keyof T ? T[K] : never;\n";
  const quote = (value: string) =>
    '"' +
    Array.from(value)
      .map((c) => {
        const n = c.codePointAt(0)!;
        if (c === '"' || c === "\\") return "\\" + c;
        if (n < 32 || n === 0x2028 || n === 0x2029) return "\\u{" + n.toString(16) + "}";
        return c;
      })
      .join("") +
    '"';
  let output = '// Generated by scripts/sync.ts.\nconst std = @import("std");\n';
  output +=
    "pub const astro_comment = " +
    quote(astroComment) +
    ";\npub const inferred_types = " +
    quote(inferredTypes) +
    ";\n";
  output +=
    "pub const entities = blk: {\n@setEvalBranchQuota(200000);\nbreak :blk std.StaticStringMap([]const u8).initComptime(.{\n";
  for (const [name, value] of Object.entries(entities))
    output += ".{" + quote(name) + "," + quote(value.characters) + "},\n";
  output += "});\n};\npub const events = std.StaticStringMap(void).initComptime(.{\n";
  for (const event of events) output += ".{" + quote(event) + ",{}},\n";
  output +=
    "});\npub const Case = struct { cp: u21, uppercase: bool, lowercase: bool, upper: []const u8, lower: []const u8 };\npub const cases = [_]Case{\n";
  const ranges: [number, number][] = [];
  let start = -1,
    last = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const c = String.fromCodePoint(cp),
      upper = c.toUpperCase(),
      lower = c.toLowerCase(),
      uppercase = /\p{Uppercase}/u.test(c),
      lowercase = /\p{Lowercase}/u.test(c);
    if (c !== upper || c !== lower || uppercase || lowercase)
      output +=
        ".{.cp=" +
        cp +
        ",.uppercase=" +
        uppercase +
        ",.lowercase=" +
        lowercase +
        ",.upper=" +
        quote(upper) +
        ",.lower=" +
        quote(lower) +
        "},\n";
    if (/[\p{Alphabetic}\p{N}]/u.test(c)) {
      if (start < 0) start = cp;
      last = cp;
    } else if (start >= 0) {
      ranges.push([start, last]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, last]);
  output +=
    "};\npub const word_ranges = [_][2]u21{\n" +
    ranges.map(([a, b]) => ".{" + a + "," + b + "},").join("\n") +
    "\n};\n";
  // Formatting a file avoids truncated streamed stdin on Windows.
  fs.mkdirSync(path.join(root, ".tmp"), { recursive: true });
  const temporary = fs.mkdtempSync(path.join(root, ".tmp/tsx-data-"));
  const generated = path.join(temporary, "tsx_data.zig");
  try {
    fs.writeFileSync(generated, output);
    await $`zig fmt ${generated}`.cwd(root).quiet("stdout");
    const formatted = fs.readFileSync(generated, "utf8");
    return formatted;
  } finally {
    if (fs.existsSync(generated)) fs.unlinkSync(generated);
    fs.rmdirSync(temporary);
  }
}

// Keep Yuku's complete ESTree conversion, including uncommon TypeScript nodes.
// Project Astro dialect nodes, share the UTF-16 position table and decode selected
// region roots from the shared document tree.
export function estreeDecoderSource(source: string, revision: string): string {
  const entitiesStart = source.indexOf("const JSX_ENTITY_NAMES =");
  const entitiesEnd = source.indexOf("class TokenList", entitiesStart);
  assert.ok(entitiesStart >= 0 && entitiesEnd > entitiesStart, "Missing Yuku JSX text decoder");
  const tables =
    source.slice(source.indexOf("const NULL ="), source.indexOf("const TokenKind =")) +
    source.slice(entitiesStart, entitiesEnd);
  const decoders = source.slice(
    source.indexOf("function shaped("),
    source.indexOf("function decode("),
  );
  let context = source.slice(
    source.indexOf("function decode("),
    source.indexOf("  const _nodesU32 ="),
  );
  context = context
    .replace(
      "function decode(buffer, source, path, shapes)",
      "function createDecoder(buffer, source, markup, astro, offsets)",
    )
    .replace("new Uint8Array(buffer)", "new Uint8Array(buffer, 12)")
    .replace(
      "new Int32Array(buffer, 0, buffer.byteLength >> 2)",
      "new Int32Array(buffer, 12, new DataView(buffer).getUint32(8, true) >> 2)",
    )
    .replace("  const _src = source;", "  const shapes = null;\n  const _src = source;")
    .replace("buildPosMap(_src, _srcLen, _firstNa)", "offsets")
    .replace(
      "  function _decode(i, depth) {",
      "  function _decode(i, depth) {\n    if (markup.has(i)) return astro(markup.get(i));",
    )
    .replace(
      "  const _inner = _attached ? nodeWithComments : _decode;",
      `  function jsonNode(i, depth) {
    const value = _decode(i, depth);
    if (value?.type === "Literal" && (typeof value.value === "bigint" || value.regex || typeof value.value === "number" && !Number.isFinite(value.value))) value.value = null;
    if (value?.regex && value.start === 0 && value.end === 0) value.raw = null;
    return value;
  }
  const _inner = jsonNode;`,
    );
  // Astro restores selected region roots and projects its dialect nodes from document metadata.
  // Keep the ordinary decoder path so uncommitted or unrelated forest nodes are not materialized.
  context = context.replace(/  let _owned, _ownedBits;[\s\S]*?(?=  function _decode\()/, "");
  const indexed = /  const node = [\s\S]*?;\n/;
  assert.ok(indexed.test(context), "Missing Yuku node dispatcher");
  context = context.replace(indexed, "  const node = _inner;\n");
  assert.ok(context.includes("if (markup.has(i))"), "Yuku decoder layout changed");
  const javascript =
    tables +
    decoders +
    context +
    "\n  _posMap();\n  return (id) => id === NULL || id === 0xffffffff ? null : node(id, 0);\n}\nexport { createDecoder };\n";
  // Upstream generates JavaScript. Add explicit types to its generated dynamic
  // records/functions so the checked-in adaptation remains TypeScript in strict mode.
  const file = ts.createSourceFile("estree_nodes.ts", javascript, ts.ScriptTarget.Latest, true);
  const any = () => ts.factory.createKeywordTypeNode(ts.SyntaxKind.AnyKeyword);
  const transformed = ts.transform(file, [
    (context) => {
      const condition = (expression: ts.Expression): ts.Expression => {
        if (
          ts.isPrefixUnaryExpression(expression) &&
          expression.operator === ts.SyntaxKind.ExclamationToken &&
          ts.isPrefixUnaryExpression(expression.operand) &&
          expression.operand.operator === ts.SyntaxKind.ExclamationToken
        )
          return expression.operand.operand;
        return expression;
      };
      const visit: ts.Visitor = (original) => {
        const node = ts.visitEachChild(original, visit, context);
        if (ts.isIfStatement(node))
          return ts.factory.updateIfStatement(
            node,
            condition(node.expression),
            node.thenStatement,
            node.elseStatement,
          );
        if (ts.isConditionalExpression(node))
          return ts.factory.updateConditionalExpression(
            node,
            condition(node.condition),
            node.questionToken,
            node.whenTrue,
            node.colonToken,
            node.whenFalse,
          );
        if (ts.isParameter(node))
          return ts.factory.updateParameterDeclaration(
            node,
            node.modifiers,
            node.dotDotDotToken,
            node.name,
            node.questionToken,
            any(),
            node.initializer,
          );
        if (
          ts.isVariableDeclaration(node) &&
          ts.isVariableDeclarationList(original.parent) &&
          (ts.isForOfStatement(original.parent.parent) ||
            ts.isForInStatement(original.parent.parent))
        )
          return node;
        if (ts.isVariableDeclaration(node))
          return ts.factory.updateVariableDeclaration(
            node,
            node.name,
            node.exclamationToken,
            any(),
            node.initializer,
          );
        if (ts.isFunctionDeclaration(node))
          return ts.factory.updateFunctionDeclaration(
            node,
            node.modifiers,
            node.asteriskToken,
            node.name,
            node.typeParameters,
            node.parameters,
            any(),
            node.body,
          );
        if (ts.isArrowFunction(node))
          return ts.factory.updateArrowFunction(
            node,
            node.modifiers,
            node.typeParameters,
            node.parameters,
            any(),
            node.equalsGreaterThanToken,
            node.body,
          );
        return node;
      };
      return (node) => ts.visitNode(node, visit) as ts.SourceFile;
    },
  ]);
  const output = ts.createPrinter().printFile(transformed.transformed[0]);
  transformed.dispose();
  return (
    `// Generated by scripts/sync.ts from Yuku ${revision}.\n// Yuku's tools/estree/decoder.zig (MIT); copyright (c) 2026 Yuku. See LICENSE.\n// Uniform generated decoder signatures and preallocated arrays follow upstream.\n/* oxlint-disable no-unused-vars, unicorn/no-new-array */\n` +
    output
  );
}

async function estreeDecoder(): Promise<string> {
  const dependency = readFileSync(join(root, "build.zig.zon"), "utf8");
  const match = /git\+([^"#]+)#([0-9a-f]{40})/.exec(dependency);
  assert.ok(match, "Missing pinned Yuku dependency");
  const source = await repository(match[1], match[2], ".tmp/yuku-source");
  const [decoder] = await readBlobs(source, match[2], ["packages/yuku/core/decode.js"]);
  return estreeDecoderSource(decoder.toString("utf8"), match[2]);
}

export async function generatedFiles(): Promise<Map<string, string>> {
  return new Map([
    ["src/transfer_nodes.ts", await transferDecoder()],
    ["src/estree_nodes.ts", await estreeDecoder()],
    ["src/tsx_data.zig", await tsxData()],
  ]);
}

async function repository(repository: string, revision: string, folder: string): Promise<string> {
  const source = resolve(root, folder);
  if (!fs.existsSync(join(source, ".git"))) {
    mkdirSync(source, { recursive: true });
    await $`git init ${source}`.quiet();
  }
  const found = await $`git -C ${source} cat-file -e ${revision + "^{commit}"}`.quiet().noThrow();
  if (found.code !== 0) await $`git -C ${source} fetch --depth=1 ${repository} ${revision}`;
  return source;
}

// Read raw Git blobs in one process, preserving whitespace and CRLF fixtures.
async function readBlobs(source: string, revision: string, files: string[]): Promise<Buffer[]> {
  const blobs = Buffer.from(
    await $`git -C ${source} cat-file --batch`
      .stdinText(files.map((file) => revision + ":" + file + "\n").join(""))
      .bytes(),
  );
  let offset = 0;
  const result = files.map((file) => {
    const newline = blobs.indexOf(10, offset);
    assert.ok(newline >= offset, "Missing Git blob header: " + file);
    const header = /^([0-9a-f]{40}) blob (\d+)$/.exec(blobs.toString("utf8", offset, newline));
    assert.ok(header, "Unexpected Git blob header: " + file);
    const end = newline + 1 + Number(header[2]);
    const contents = blobs.subarray(newline + 1, end);
    assert.strictEqual(contents.length, Number(header[2]));
    assert.strictEqual(
      createHash("sha1")
        .update("blob " + contents.length + "\0")
        .update(contents)
        .digest("hex"),
      header[1],
      file,
    );
    assert.strictEqual(blobs[end], 10);
    offset = end + 1;
    return contents;
  });
  assert.strictEqual(offset, blobs.length);
  return result;
}

async function syncBiome(source: string, revision: string): Promise<void> {
  const destination = resolve(root, "test/fixtures/biome");
  const git = (...args: string[]) => new CommandBuilder().command(["git", "-C", source, ...args]);
  const paths = (await git("ls-tree", "-r", "--name-only", "-z", revision).text())
    .split("\0")
    .filter((file) => file.startsWith("crates/") && /\.(astro|astro_expr\.tsx)$/.test(file))
    .sort();
  assert.ok(paths.length > 0, "No Biome Astro fixtures found");

  // These diagnostic differences were checked against @astrojs/compiler-rs 0.5.2.
  // Biome's HTML tests parse the host language; our parse API also validates JS.
  const html = "crates/biome_html_parser/tests/html_specs/";
  const js = "crates/biome_js_parser/tests/js_test_suite/";
  const differences: Record<string, { errors: boolean; tsxErrors?: boolean; reason: string }> = {
    [html + "error/astro/missing_fence.astro"]: {
      errors: false,
      reason:
        "The reference Astro parse API treats an unclosed frontmatter fence as template text.",
    },
    [html + "error/astro/processing_instruction_bogus_attribute.astro"]: {
      errors: false,
      tsxErrors: false,
      reason: "The reference Astro parser treats processing instructions as template text.",
    },
    [html + "error/astro/processing_instruction_unclosed.astro"]: {
      errors: false,
      tsxErrors: false,
      reason: "The reference Astro parser treats processing instructions as template text.",
    },
    [html + "error/astro/stray_closing_tag_at_root.astro"]: {
      errors: false,
      reason:
        "The reference Astro parse API stops at stray root closing tags without a diagnostic.",
    },
    [html + "ok/astro/closing_tag_name_case.astro"]: {
      errors: true,
      tsxErrors: true,
      reason: "The reference Astro parser matches tag names case-sensitively.",
    },
    [html + "ok/astro/frontmatter_extra_dashes.astro"]: {
      errors: true,
      tsxErrors: true,
      reason:
        "The reference Astro parser consumes three fence dashes; the fourth enters JS or template text.",
    },
    [js + "ok/astro_raw_text_end_tag.astro_expr.tsx"]: {
      errors: true,
      reason:
        "The reference Astro parse API validates the script body; Biome tests only raw-text boundaries here.",
    },
    [js + "ok/astro_is_raw_end_tag_name_boundary.astro_expr.tsx"]: {
      errors: true,
      reason:
        "The reference Astro raw-text reader accepts a closing-name prefix; the trailing closing tag then enters JavaScript recovery.",
    },
  };
  for (const file of Object.keys(differences)) assert.ok(paths.includes(file), file);
  const tsxDifferences: Record<string, { errors: boolean; reason: string }> = {
    [html + "ok/astro/object_literal_expression.astro"]: {
      errors: false,
      reason:
        "Published astro2tsx 0.1.3 duplicates HTML shorthand text literally, including object expressions, even when the resulting TSX is invalid.",
    },
    [js + "ok/astro_quote_leading_attribute_double_quote.astro_expr.tsx"]: {
      errors: true,
      reason:
        "Published astro2tsx 0.1.3 treats the leading quote as an unterminated string; the newer Biome fixture permits a quote in an attribute name.",
    },
    [js + "ok/astro_quote_leading_attribute_name.astro_expr.tsx"]: {
      errors: true,
      reason:
        "Published astro2tsx 0.1.3 treats the leading quote as an unterminated string; the newer Biome fixture permits a quote in an attribute name.",
    },
    [js + "ok/astro_quote_leading_attribute_self_closing.astro_expr.tsx"]: {
      errors: true,
      reason:
        "Published astro2tsx 0.1.3 treats the leading quote as an unterminated string; the newer Biome fixture permits a quote in an attribute name.",
    },
    [js + "ok/astro_shorthand_attribute_expression.astro_expr.tsx"]: {
      errors: true,
      reason:
        "Published astro2tsx 0.1.3 permits only simple JSX shorthand names; the newer Biome fixture permits expressions.",
    },
  };
  for (const file of Object.keys(tsxDifferences)) assert.ok(paths.includes(file), file);

  const blobs = await readBlobs(source, revision, paths);
  const fixtures = paths.map((file, index) => {
    const contents = blobs[index];
    const target = join(destination, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
    const parserTest = file.includes("_parser/tests/");
    const biomeErrors = parserTest ? file.includes("/error/") : null;
    const difference = differences[file];
    const kind = file.endsWith(".astro_expr.tsx") ? "expression" : "document";
    return {
      file,
      sha256: createHash("sha256").update(contents).digest("hex"),
      kind,
      suite: file.split("/")[1],
      biomeErrors,
      parseErrors: difference?.errors ?? biomeErrors ?? false,
      tsxErrors: tsxDifferences[file]?.errors ?? difference?.tsxErrors ?? biomeErrors ?? false,
      ...(tsxDifferences[file] ? { tsxDiagnosticDifference: tsxDifferences[file].reason } : {}),
      ...(difference ? { diagnosticDifference: difference.reason } : {}),
      ...(file === js + "ok/astro_quote_leading_attribute_double_quote.astro_expr.tsx"
        ? { parseThrows: "SyntaxError" }
        : {}),
    };
  });
  const origin = {
    repository: "https://github.com/biomejs/biome",
    revision,
    license: "MIT",
    referenceParser: "@astrojs/compiler-rs@0.5.2",
    referenceTsx: "@astrojs/astro2tsx@0.1.3",
    expressionWrapper: { prefix: "{\n", suffix: "\n}" },
    fixtures,
  };
  const manifest = JSON.stringify(origin, null, 2) + "\n";
  writeFileSync(join(destination, "origin.json"), manifest);
}

async function syncCompiler(source: string, revision: string): Promise<void> {
  const prefix = "crates/astro_codegen/tests/fixtures/";
  const git = (...args: string[]) => new CommandBuilder().command(["git", "-C", source, ...args]);
  const files = (await git("ls-tree", "-r", "--name-only", "-z", revision).text())
    .split("\0")
    .filter((file) => file.startsWith(prefix) && file.endsWith(".astro"))
    .sort();
  assert.ok(files.length > 0, "No compiler transform fixtures found");
  const blobs = await readBlobs(source, revision, files);
  const fixtures = [];
  for (const [index, file] of files.entries()) {
    const contents = blobs[index];
    const name = file.slice(prefix.length);
    const destination = join(root, "test/fixtures/transform-upstream/fixtures", name);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, contents);
    fixtures.push({ file: name, sha256: createHash("sha256").update(contents).digest("hex") });
  }
  writeFileSync(
    join(root, "test/fixtures/transform-upstream/origin.json"),
    JSON.stringify(
      {
        repository: compilerOrigin.repository,
        revision,
        license: "MIT",
        directory: prefix,
        fixtures,
      },
      null,
      2,
    ) + "\n",
  );
}

