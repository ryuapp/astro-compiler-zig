const std = @import("std");
const ast = @import("parser").ast;
const wire = @import("yuku_transfer");
const astro = @import("astro");

comptime {
    std.debug.assert(@sizeOf(wire.Header) == 40);
    std.debug.assert(@sizeOf(wire.PackedNode) == 48);
    std.debug.assert(@sizeOf(wire.PackedComment) == 24);
    std.debug.assert(@sizeOf(ast.Token) == 16);
    std.debug.assert(@import("meta").fields(ast.NodeData).len <= 256);
}

pub fn main() void {
    @setEvalBranchQuota(2_000_000);
    std.debug.print("// Generated by scripts/generate-transfer.zig.\nimport type {{ Reader }} from './transfer_decode.ts';\n", .{});
    inline for (@import("meta").fields(ast.NodeData), 0..) |tag, tag_index| {
        if (@typeInfo(tag.type) == .@"struct") {
            inline for (@import("meta").fields(tag.type), 0..) |field, field_index| {
                const T = if (field.type == ?ast.ImportPhase) ast.ImportPhase else field.type;
                if (comptime @typeInfo(T) == .@"enum" and T != ast.NodeIndex) {
                    std.debug.print("const e{d}_{d}: Record<number, string> = {s};\n", .{
                        tag_index, field_index, comptime enumExpression(T),
                    });
                }
            }
        }
    }
    std.debug.print("function node(tag: number,w: Uint32Array,i: number,f: number) {{\n    switch(tag) {{\n", .{});
    inline for (@import("meta").fields(ast.NodeData), 0..) |tag, tag_index| {
        std.debug.print("    case {d}: return {{{s}:{s}}};\n", .{
            tag_index, tag.name, comptime payloadExpression(tag.type, tag_index),
        });
    }
    std.debug.print("    default: throw new Error('Invalid Yuku node tag');\n    }}\n}}\n", .{});
    std.debug.print("const tokenTags: Record<number, string> = {s};\n", .{comptime enumExpression(ast.TokenTag)});
    std.debug.print("const layout = {{\n", .{});
    inline for (.{
        .{ "HEADER_SIZE", @sizeOf(wire.Header) },
        .{ "NODE_SIZE", @sizeOf(wire.PackedNode) },
        .{ "NODE_FLAGS_OFFSET", @offsetOf(wire.PackedNode, "flags") },
        .{ "NODE_SPAN_START_U32", @offsetOf(wire.PackedNode, "span_start") / 4 },
        .{ "NODE_SPAN_END_U32", @offsetOf(wire.PackedNode, "span_end") / 4 },
        .{ "COMMENT_SIZE", @sizeOf(wire.PackedComment) },
        .{ "COMMENT_FLAGS_OFFSET", @offsetOf(wire.PackedComment, "flags") },
        .{ "COMMENT_VALUE_START_OFFSET", @offsetOf(wire.PackedComment, "value_start") },
        .{ "COMMENT_VALUE_END_OFFSET", @offsetOf(wire.PackedComment, "value_end") },
        .{ "COMMENT_SPAN_START_OFFSET", @offsetOf(wire.PackedComment, "span_start") },
        .{ "COMMENT_SPAN_END_OFFSET", @offsetOf(wire.PackedComment, "span_end") },
        .{ "TOKEN_SIZE", @sizeOf(ast.Token) },
        .{ "TOKEN_START_U32", @offsetOf(ast.Token, "span") / 4 },
        .{ "TOKEN_END_U32", (@offsetOf(ast.Token, "span") + 4) / 4 },
        .{ "TOKEN_TAG_U32", @offsetOf(ast.Token, "tag") / 4 },
        .{ "TOKEN_FLAGS_U32", @offsetOf(ast.Token, "flags") / 4 },
        .{ "FLAG_ATTACHED_COMMENTS", wire.FLAG_ATTACHED_COMMENTS },
    }) |entry| std.debug.print("    {s}: {d},\n", .{ entry[0], entry[1] });
    std.debug.print("    TOKEN_EOF_TAG: {d},\n", .{@backingInt(ast.TokenTag.eof)});
    std.debug.print("}};\n", .{});
    std.debug.print("const dictionary = [", .{});
    for (astro.transfer.dictionary) |item| std.debug.print("'{s}',", .{item});
    std.debug.print("];\n", .{});
    const Label = @typeInfo(@FieldType(astro.AstroDiagnostic, "labels")).pointer.child;
    const Span = @FieldType(Label, "span");
    emitRecord(astro.AstroNode, "astroNode");
    emitRecord(astro.AstroAttribute, "attribute");
    emitRecord(astro.AstroDiagnostic, "diagnostic");
    emitRecord(Label, "label");
    emitRecord(Span, "span");
    std.debug.print(
        "export {{node,tokenTags,layout,dictionary,astroNode,diagnostic}};\n",
        .{},
    );
}

fn enumExpression(comptime T: type) []const u8 {
    var expression: []const u8 = "{";
    for (@import("meta").fields(T)) |field| {
        expression = expression ++ std.fmt.comptimePrint("{d}:'{s}',", .{
            field.value, field.name,
        });
    }
    return expression ++ "}";
}

fn payloadExpression(comptime T: type, comptime tag: usize) []const u8 {
    if (T == void) return "null";
    var expression: []const u8 = "{";
    for (@import("meta").fields(T), 0..) |field, index| {
        expression = expression ++ field.name ++ ":" ++ packedExpression(T, index, tag) ++ ",";
    }
    return expression ++ "}";
}

fn packedExpression(comptime T: type, comptime index: usize, comptime tag: usize) []const u8 {
    const F = @import("meta").fields(T)[index].type;
    const slot = wire.layout(T, index).slot + @offsetOf(wire.PackedNode, "slots") / 4;
    const bit = wire.layout(T, index).bit;
    const first = std.fmt.comptimePrint("w[i+{d}]", .{slot});
    const second = std.fmt.comptimePrint("w[i+{d}]", .{slot + 1});
    if (F == ast.NodeIndex) return first;
    if (F == ast.String) return "{start:" ++ first ++ ",end:" ++ second ++ "}";
    if (F == ast.IndexRange) return "{start:" ++ first ++ ",len:" ++ second ++ "}";
    const presence = std.fmt.comptimePrint("(f&{d})", .{@as(u32, 1) << bit});
    if (F == bool) return "!!" ++ presence;
    if (F == ?ast.Hashbang) {
        return presence ++ "?{value:{start:" ++ first ++ ",end:" ++ second ++ "}}:null";
    }
    const optional = F == ?ast.ImportPhase;
    const E = if (optional) ast.ImportPhase else F;
    const bits = wire.enumBitWidth(E);
    const lookup = std.fmt.comptimePrint("e{d}_{d}[(f>>{d})&{d}]", .{
        tag, index, bit + @intFromBool(optional), (@as(u32, 1) << bits) - 1,
    });
    return if (optional) presence ++ "?" ++ lookup ++ ":null" else lookup;
}

fn camelCase(comptime name: []const u8) []const u8 {
    var result: []const u8 = "";
    var uppercase = false;
    for (name) |character| {
        if (character == '_') {
            uppercase = true;
        } else {
            result = result ++ [1]u8{if (uppercase) std.ascii.toUpper(character) else character};
            uppercase = false;
        }
    }
    return result;
}

fn emitRecord(comptime T: type, comptime name: []const u8) void {
    std.debug.print("function {s}(r: Reader) {{return {{\n", .{name});
    inline for (@import("meta").fields(T)) |field| {
        std.debug.print("    {s}:{s},\n", .{
            comptime camelCase(field.name), comptime nativeExpression(field.type),
        });
    }
    std.debug.print("}};}}\n", .{});
}

fn nativeExpression(comptime T: type) []const u8 {
    return switch (@typeInfo(T)) {
        .bool => "!!r.u8()",
        .int => "r.u32()",
        .optional => |optional| "(r.u8()?" ++ nativeExpression(optional.child) ++ ":null)",
        .pointer => |pointer| if (pointer.child == u8)
            "r.string()"
        else if (pointer.child == u32)
            "r.integers()"
        else
            "r.array(" ++ recordName(pointer.child) ++ ")",
        .@"struct" => recordName(T) ++ "(r)",
        else => @compileError("Unsupported wire type " ++ @typeName(T)),
    };
}

fn recordName(comptime T: type) []const u8 {
    if (T == astro.AstroAttribute) return "attribute";
    const Label = @typeInfo(@FieldType(astro.AstroDiagnostic, "labels")).pointer.child;
    if (T == Label) return "label";
    if (T == @FieldType(Label, "span")) return "span";
    @compileError("Unknown wire record " ++ @typeName(T));
}
